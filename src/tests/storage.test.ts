import { describe,expect,it } from 'vitest';
import { mkdtemp,readFile,rm,stat,utimes } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { withTemplateMutation } from '../lib/task-control';

describe('SQLite 和模板真实持久化',()=>{
  it('模板、模型表、对话和导出历史能保存及读取',async()=>{
    const dir=await mkdtemp(path.join(os.tmpdir(),'ai-design-test-'));
    process.env.AI_DESIGN_DATA_DIR=dir;
    const storage=await import('../lib/storage');
    const draftId=randomUUID();
    const source={html:'<h1>{{title}}</h1>',css:'h1{color:white}',manifest:{name:'原稿',width:640,height:800,fields:[{key:'title',label:'标题',type:'text' as const}],listFields:{}}};
    try{
      await storage.writeSource('drafts',draftId,source,Buffer.from('png'));
      const id=await storage.saveDraft(draftId,'测试');
      expect(storage.listTemplates().length).toBe(1);
      expect((await storage.readSource('templates',id)).html).toBe(source.html);
      storage.renameTemplate(id,'修改后');
      expect(storage.listTemplates()[0].name).toBe('修改后');
      const id2=await storage.duplicateTemplate(id);
      expect(storage.listTemplates()).toHaveLength(2);
      storage.replaceModels([{name:'deepseek-v4.1-flash',discount:'4折'},{name:'kimi-k3',discount:'5折'}]);
      expect(storage.getModels()[0]).toEqual({name:'deepseek-v4.1-flash',discount:'4折'});
      storage.replaceModels([{name:'glm-5.3',discount:'7折'}]);
      expect(storage.getModels()).toEqual([{name:'glm-5.3',discount:'7折'}]);
      const png=Buffer.from('example-png');
      const posterId=await storage.savePoster(png,id,2);
      expect((await storage.readPoster(posterId)).equals(png)).toBe(true);
      expect(storage.listPosters()[0]).toMatchObject({id:posterId,templateName:'修改后',modelCount:2});
      const threadId=storage.saveChatExchange(undefined,'帮我分析海报',null,'建议突出折扣。');
      expect(storage.listChats()[0].id).toBe(threadId);
      storage.saveChatExchange(threadId,'再提一个方案',null,'增加光效。');
      expect(storage.getChat(threadId).map(x=>x.content)).toEqual(['帮我分析海报','建议突出折扣。','再提一个方案','增加光效。']);
      const state={referencePath:'/api/assets/references/test.png',draftId,templateId:id,width:1080,height:1440};
      storage.saveStudioState(threadId,state);
      expect(storage.getStudioState(threadId)).toEqual(state);
      const task=storage.beginStudioRun(threadId,'测试后台任务',null,{referencePath:'',draftId,templateId:id,width:1080,height:1440});
      expect(storage.getChat(threadId).at(-1)?.content).toBe('测试后台任务');
      const eventId=storage.recordStudioEvent(task.runId,'tool',{toolName:'convertToTemplate',status:'completed'});
      expect(storage.readRunEvents(task.runId).at(-1)?.id).toBe(eventId);
      expect(storage.recentStudioEvents(threadId).some(x=>x.type==='tool')).toBe(true);
      storage.finishStudioRun(task.runId,'转换成功','completed');
      expect(storage.getStudioRun(task.runId)?.status).toBe('completed');
      storage.savePosterDraft({templateId:id,selectedNames:['deepseek-v4.1-flash'],fixedFields:{title:'限时优惠'}});
      expect(storage.getPosterDraft()?.fixedFields.title).toBe('限时优惠');
      const original=await storage.readSource('templates',id);
      const version=await storage.snapshotTemplate(id);
      await storage.writeSource('templates',id,{...original,html:'<h1>新的模板</h1>'},Buffer.from('newpng'));
      expect((await storage.readSource('templates',id)).html).toBe('<h1>新的模板</h1>');
      await storage.restoreTemplateVersion(id,version.id);
      expect((await storage.readSource('templates',id)).html).toBe(original.html);
      expect(storage.listTemplateVersions(id)).toHaveLength(2);
      const htmlPath=path.join(dir,'templates',id,'template.html');
      const oldTime=new Date('2023-01-01T00:00:00Z');
      await utimes(htmlPath,oldTime,oldTime);
      const beforePatch=await storage.readSource('templates',id);
      const changed=await storage.writeSourcePatch('templates',id,beforePatch,{...beforePatch,css:'h1{color:orange}'},Buffer.from('preview2'));
      expect(changed).toEqual(['css']);
      expect((await storage.readSource('templates',id)).html).toBe(beforePatch.html);
      expect((await stat(htmlPath)).mtimeMs).toBeCloseTo(oldTime.getTime(),-2);
      expect((await storage.readSource('templates',id)).css).toBe('h1{color:orange}');
      const usage=await import('../lib/model-usage');
      usage.saveModelPrices('vision',{inputPerMillion:2,outputPerMillion:8,cachedInputPerMillion:1,perImage:null});
      usage.recordModelUsage({runId:task.runId,kind:'vision',operation:'template-patch',modelId:'test-vision',usage:{inputTokens:1000,outputTokens:400,inputTokenDetails:{cacheReadTokens:600}},durationMs:1900});
      const entry=usage.listModelUsage(1)[0];
      expect(entry.inputTokens).toBe(1000);
      expect(entry.cacheReadTokens).toBe(600);
      expect(entry.estimatedCostCny).toBeCloseTo((400*2+600*1+400*8)/1_000_000);
      usage.recordModelUsage({kind:'image',operation:'image-generate',modelId:'test-image',imageCount:1,durationMs:10});
      expect(usage.listModelUsage(1)[0].estimatedCostCny).toBeNull();
      let release!:()=>void;
      const edit=withTemplateMutation(id,()=>new Promise<void>(resolve=>{release=resolve}));
      await expect(storage.deleteTemplate(id)).rejects.toThrow('正在被修改');
      await expect(storage.restoreTemplateVersion(id,version.id)).rejects.toThrow('正在被修改');
      expect((await storage.readSource('templates',id)).css).toBe('h1{color:orange}');
      release();
      await edit;
      storage.deleteChat(threadId);
      expect(storage.getStudioState(threadId)).toEqual({referencePath:'',draftId:'',templateId:'',width:1080,height:1440});
      expect(storage.getChat(threadId)).toHaveLength(0);
      await storage.deleteTemplate(id);
      await storage.deleteTemplate(id2);
      expect(storage.listTemplates()).toHaveLength(0);
    }finally{await rm(dir,{recursive:true,force:true})}
  });
});
